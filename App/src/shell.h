#pragma once
// Каркас окна: верхняя панель, вкладки внизу, полоса состояния, а между
// ними -- экран.
//
// Порт `ui/MainWindow.kt` вместе с тремя её частями: `MainTopAppBar`,
// `MainBottomBar` и `StatusBar`. Устройство то же самое, вплоть до правила
// показа: панели видны только на верхнем уровне, а стоит открыть форум или
// тему -- остаются экран и полоса состояния, потому что у тех экранов свой
// заголовок со стрелкой назад.
//
// Часть кнопок пока ни к чему не ведёт, и это нормальное состояние порта:
// каркас ставится целиком, наполнение приходит по одному. Что за какой
// кнопкой должно появиться, написано у места.

#include <functional>
#include <string>
#include <string_view>
#include <vector>

#include "pch.h"

namespace besedka::app {

/// Что известно про сервер. Порт `ui/components/ServerStatus.kt`: до первого
/// ответа неизвестно, дальше -- ответил или не ответил.
enum class ServerStatus { unknown, online, offline };

/// Вкладки нижней панели, в порядке jana.
enum class Tab { forums, watched, outbox };

class Shell {
public:
    Shell();

    /// Корень, который отдаётся окну как содержимое. Окно получает его один
    /// раз: дальше меняется не содержимое окна, а середина каркаса.
    const wxl::UIElement& root() const { return root_.value(); }

    // ---- стопка открытых страниц ----
    //
    // Страницы лежат стопкой: открыть значит положить сверху, «назад» --
    // снять верхнюю. Показывается стопка одним из двух способов, и выбирает
    // способ ширина окна: уже 1200 логических -- видна верхняя страница, шире
    // -- две последние, предпоследняя слева и верхняя справа. Стопка от
    // ширины не зависит вовсе, поэтому растяжка окна ничего не открывает и не
    // закрывает.

    /// Страница стопки: её корень и то, чем ей сообщают, где она встала.
    ///
    /// Правая половина -- та, в которой читают, поэтому выбирают в ней
    /// двойным щелчком: одиночный принадлежит содержимому. Знать об этом
    /// должен сам экран, а сказать ему может только тот, кто раскладывает
    /// страницы, -- отсюда обработчик рядом с корнем. У страниц, в которых
    /// не выбирают (заглушки, сообщения темы), он пуст.
    struct Page {
        wxl::UIElement root;
        std::function<void(bool secondary)> placed;
    };

    /// Заставка: одна страница на всё окно и без панелей. Отдельный вызов, а
    /// не `showRoot` с флагом: заставка -- это не верхний уровень вкладки, а
    /// то, что показывают вместо всего, пока показывать нечего.
    void showSplash(const wxl::UIElement& page);

    /// Верхний уровень вкладки: стопка начинается заново с этой страницы.
    void showRoot(Page page);

    /// Открыть страницу: положить на стопку.
    void open(Page page);

    /// Назад: снять верхнюю. Нижнюю не снимает -- ниже верхнего уровня
    /// вкладки идти некуда.
    void back();

    /// Сколько страниц в стопке. Экрану нужно, чтобы решить, показывать ли
    /// себе стрелку возврата.
    std::size_t depth() const { return stack_.size(); }

    /// Кружок у названия: отвечает сервер или нет.
    void setServerStatus(ServerStatus status);

    /// Идёт запрос -- вместо кнопки обновления колечко, как в jana.
    void setBusy(bool busy);

    /// Полоса внизу окна. У jana туда попадает адрес ссылки под указателем;
    /// у нас пока -- то, что стоит сказать, не заводя окна с сообщением.
    void setStatusText(std::wstring_view said);

    /// Ширина, под которую раскладывать страницы, в логических пикселях.
    /// Приходит от окна из WM_SIZE -- то есть до того, как XAML возьмётся за
    /// вёрстку. У элемента её не спрашиваем: SizeChanged приходит уже изнутри
    /// прохода вёрстки, а перекладывать дерево оттуда нельзя.
    void setWidth(double logical);

    /// Доля левой страницы в ширине середины, 0,2…0,8. Ставит запуск из
    /// настроек и двигает читатель, потянув границу.
    void splitFraction(double value);
    double splitFraction() const { return fraction_; }

    /// Читатель отпустил границу на новом месте -- долю пора запомнить.
    std::function<void(double)> onSplitChanged;

    std::function<void()> onRefresh;
    std::function<void(Tab)> onTab;
    std::function<void()> onLogin;
    std::function<void()> onAbout;

private:
    /// Хватает ли ширины на две страницы.
    bool isWide() const;

    /// Пересобрать середину под нынешние ширину и стопку.
    void relayout();

    /// Панели видны, пока слева стоит верхний уровень вкладки: вкладки внизу
    /// принадлежат именно ей, и прятать их, когда список форумов на экране,
    /// незачем. В одностраничном показе это стопка из одной страницы, в
    /// двухстраничном -- из одной или двух.
    void updateChrome();

    std::vector<Page> stack_;
    bool splash_ = false;      ///< на экране заставка: без панелей и без стопки
    bool wide_ = false;        ///< показ двухстраничный
    double width_ = 0;         ///< ширина под страницы, логические пиксели
    double fraction_ = 0.5;    ///< доля левой страницы

    // Тяга границы. Захват указателя делает её тягой, а не «пока мышь над
    // полоской»: полоска шириной в шесть пикселей теряет мышь на первом же
    // быстром движении.
    bool dragging_ = false;

    wxl::Nullable<wxl::Grid> root_ = nullptr;
    wxl::Nullable<wxl::Border> topBar_ = nullptr;
    wxl::Nullable<wxl::Grid> host_ = nullptr;
    wxl::Nullable<wxl::Border> splitter_ = nullptr;
    wxl::Nullable<wxl::Border> tabsBar_ = nullptr;
    wxl::Nullable<wxl::Border> statusBar_ = nullptr;
    wxl::Nullable<wxl::SelectorBar> tabs_ = nullptr;
    wxl::Nullable<wxl::TextBlock> status_ = nullptr;
    wxl::Nullable<wxl::Border> dot_ = nullptr;
    wxl::Nullable<wxl::Button> refresh_ = nullptr;
    wxl::Nullable<wxl::ProgressRing> ring_ = nullptr;
    wxl::Nullable<wxl::Button> theme_ = nullptr;
};

}  // namespace besedka::app
