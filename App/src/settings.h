#pragma once
// Настройки Беседки: то, чем она открывается.
//
// Пока в файле одно — место окна, — и это не заготовка на будущее, а всё, что
// у приложения сейчас есть своего. Хранилище тем, форумов и прочитанного будет
// отдельным и большим; настройки же обязаны быть маленькими и читаться до
// первого кадра, потому что окно надо поставить туда, где его оставили, ещё до
// того, как оно покажется.
//
// Формат — XML, разбираемый `wxl::xml`: читатель у нас уже есть, он проверяет
// документ целиком до разбора и берёт память из STA-пула, который создаётся всё
// равно. Запись своя, в двадцать строк, потому что формат наш.
//
// Битый файл, файл от будущей версии, файл, который правили руками, — всё это
// повод открыться со значениями по умолчанию, а не повод не открыться.

#include <filesystem>
#include <string>

namespace besedka::app {

/// Всё, что лежит в settings.xml.
struct Settings {
    /// Версия формата. Незнакомое поле не роняет разбор — это она и покупает.
    static constexpr int kVersion = 1;

    /// Где стояло окно и в каком было состоянии. Текст непрозрачный: его
    /// выдаёт и принимает обратно wxl (см. `wxl::window_placement`), а
    /// приложению достаточно донести его от файла до окна и обратно.
    std::wstring windowPlacement;

    /// Где стоит граница между страницами в двухстраничном показе: доля
    /// левой, 0,2…0,8. Доля, а не пиксели, потому что окно растягивают и
    /// переносят на другой монитор, и число пикселей на каждом из них
    /// означало бы разное.
    double splitFraction = 0.5;
};

/// Каталог данных: `%LOCALAPPDATA%\Besedka`.
///
/// Не Roaming: место окна привязано к монитору этой машины, и переносить его
/// на другую было бы не услугой, а сюрпризом.
std::filesystem::path dataDirectory();

/// Путь к settings.xml.
std::filesystem::path settingsPath();

/// Читает settings.xml. Нет файла, битый файл — вернутся умолчания.
Settings loadSettings();

/// Пишет settings.xml целиком: временный файл рядом, сброс на носитель,
/// потом замена. Сброс до переименования — не педантизм: без него выключение
/// питания оставило бы переименование сделанным, а содержимое — нет.
void saveSettings(const Settings& settings);

}  // namespace besedka::app
